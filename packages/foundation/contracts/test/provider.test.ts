/**
 * Golden fixtures for the provider-facing contracts (architecture §4, §7, §8).
 * These are the types that cross the process boundary, so they get the same
 * treatment as events: one fixture each, parsed by its schema, re-encoded to
 * the same value.
 */

import assert from 'node:assert/strict'
import { readFileSync, readdirSync } from 'node:fs'
import { test } from 'node:test'
import { decode, decodeStrict, parse, SchemaError, type Schema } from '@fleet/foundation-core'
import {
  briefHandoff,
  mcpServer,
  providerCapabilities,
  providerEvent,
  sessionSpec,
  stateFile,
  turn,
  usage,
  toolPolicy,
  defaultToolPolicy,
} from '../src/index.ts'

const providerEventsDir = new URL('./fixtures/provider-events/', import.meta.url)
const providerDir = new URL('./fixtures/provider/', import.meta.url)

const fixture = (dir: URL, name: string): unknown => JSON.parse(readFileSync(new URL(`${name}.json`, dir), 'utf8'))

const fixtureNames = (dir: URL): string[] =>
  readdirSync(dir)
    .filter((name) => name.endsWith('.json'))
    .map((name) => name.slice(0, -'.json'.length))
    .sort()

/** The provider stream is a discriminated union, so a fixture is named by its `type`. */
const providerEventTypes = [
  'approval.abandoned',
  'approval.requested',
  'compaction',
  'error',
  'question.asked',
  'question.abandoned',
  'session.ended',
  'tool.denied',
  'tool.use',
  'turn.ended',
  'turn.started',
] as const

/** The rest of §4's vocabulary, by fixture name. */
const contracts: Readonly<Record<string, () => Schema<unknown>>> = {
  'brief-handoff': briefHandoff as () => Schema<unknown>,
  'mcp-server': mcpServer as () => Schema<unknown>,
  'provider-capabilities': providerCapabilities as () => Schema<unknown>,
  'session-spec': sessionSpec as () => Schema<unknown>,
  'state-file': stateFile as () => Schema<unknown>,
  'tool-policy': toolPolicy as () => Schema<unknown>,
  turn: turn as () => Schema<unknown>,
  usage: usage as () => Schema<unknown>,
}

test('provider-event fixtures are exactly the union members', () => {
  assert.deepEqual(fixtureNames(providerEventsDir), [...providerEventTypes].sort())
})

for (const type of providerEventTypes) {
  test(`golden: provider event ${type}`, () => {
    const value = fixture(providerEventsDir, type)
    const parsed = parse(providerEvent(), value) as { type: string }
    assert.deepEqual(parsed, value, 'the fixture survives decode and encode unchanged')
    assert.equal(parsed.type, type, 'the union dispatches on `type`, which is why waiting_input needs no regex')
  })
}

test('the provider stream vocabulary is eleven events, and none is missing', () => {
  // Every way a question and an approval can die has a member of its own: a
  // session that ends closes what it owns, and the supervisor is told so.
  assert.equal(providerEventTypes.length, 11)
  assert.equal(new Set(providerEventTypes).size, providerEventTypes.length)
})

test('every question the stream can ask is answerable, and every approval respondable', () => {
  const asked = parse(providerEvent(), fixture(providerEventsDir, 'question.asked')) as {
    questions: readonly { question: string }[]
  }
  assert.ok(asked.questions.length > 0, 'a question.asked with nothing to choose is not a decision')
  const approval = parse(providerEvent(), fixture(providerEventsDir, 'approval.requested')) as { tool: string }
  assert.ok(approval.tool.length > 0, 'an approval that does not name the tool cannot be answered')
})

test('turn.ended says why, and only a failed turn carries an error', () => {
  const ended = fixture(providerEventsDir, 'turn.ended') as Record<string, unknown>
  assert.equal(ended.reason, 'completed')
  const failed = parse(providerEvent(), { ...ended, reason: 'failed', error: 'the process died mid-turn' })
  assert.deepEqual(failed, { ...ended, reason: 'failed', error: 'the process died mid-turn' })
  assert.throws(() => parse(providerEvent(), { ...ended, reason: 'aborted' }), SchemaError)
})

test('every provider contract has a fixture, and every fixture a contract', () => {
  assert.deepEqual(fixtureNames(providerDir), Object.keys(contracts).sort())
})

for (const [name, schema] of Object.entries(contracts)) {
  test(`golden: provider contract ${name}`, () => {
    const value = fixture(providerDir, name)
    const parsed = parse(schema(), value)
    assert.deepEqual(parsed, value)
    assert.deepEqual(parse(schema(), parsed), parsed, 'a second decode changes nothing')
  })
}

/** Generated by `generate-invalid.ts`, one mutation per event `type` (§4). */
const invalidDir = new URL('./fixtures/provider-events-invalid/', import.meta.url)

const invalidNames = readdirSync(invalidDir)
  .filter((name) => name.endsWith('.json'))
  .map((name) => name.slice(0, -'.json'.length))
  .sort()

test('invalid provider-event fixtures cover the stream exactly', () => {
  assert.deepEqual(invalidNames, [...providerEventTypes].sort(), 'one refused input per event type')
})

for (const type of providerEventTypes) {
  test(`refused: provider event ${type}`, () => {
    const { input, path } = JSON.parse(readFileSync(new URL(`${type}.json`, invalidDir), 'utf8')) as {
      input: unknown
      path: string
    }
    assert.notDeepEqual(input, fixture(providerEventsDir, type), 'the invalid input is a mutation of the golden one')

    const result = decodeStrict(providerEvent(), input)
    assert.equal(result.ok, false, 'the supervisor refuses what the provider stream cannot describe')
    if (result.ok) return
    assert.equal(result.error.issues.length, 1, `one mutation, one issue: ${result.error.message}`)
    assert.equal(result.error.issues[0]?.path, path, 'the refusal names the field that was mutated')
  })
}

test('an unknown provider-event type is refused, so the union is closed', () => {
  assert.throws(() => parse(providerEvent(), { type: 'turn.paused', turnId: 'trn_8192a3b4c5d6e7f8' }), SchemaError)
})

test('a session spec refuses a permission mode the provider vocabulary does not have', () => {
  const value = fixture(providerDir, 'session-spec') as Record<string, unknown>
  assert.throws(() => parse(sessionSpec(), { ...value, permissionMode: 'yolo' }), SchemaError)
})

test('a session spec needs a brief: a peer never starts from a bare prompt (§12)', () => {
  const value = fixture(providerDir, 'session-spec') as Record<string, unknown>
  const { brief: _brief, ...withoutBrief } = value
  assert.throws(() => parse(sessionSpec(), withoutBrief), SchemaError)
})

test('a state file needs a goal and a brief version, the two things a resumed peer must know (§8)', () => {
  const value = fixture(providerDir, 'state-file') as Record<string, unknown>
  assert.throws(() => parse(stateFile(), { ...value, goal: undefined }), SchemaError)
  assert.throws(() => parse(stateFile(), { ...value, briefVersion: 0 }), SchemaError)
})

test('a tool policy refuses an unknown action, an empty tool name and too many rules', () => {
  const schema = toolPolicy()
  assert.equal(decodeStrict(schema, { defaultAction: 'maybe', rules: [] }).ok, false)
  assert.equal(decodeStrict(schema, { defaultAction: 'allow', rules: [{ tool: '', action: 'deny' }] }).ok, false)
  assert.equal(decodeStrict(schema, { defaultAction: 'allow', rules: [{ tool: 'Bash', action: 'sometimes' }] }).ok, false)
  const many = Array.from({ length: 201 }, () => ({ tool: 'Bash', action: 'ask' }))
  assert.equal(decodeStrict(schema, { defaultAction: 'allow', rules: many }).ok, false)
})

test('a tool policy is strict on write and keeps first-match order on read', () => {
  const schema = toolPolicy()
  const policy = {
    defaultAction: 'ask',
    rules: [
      { tool: 'Bash', pattern: '^git status$', action: 'allow' },
      { tool: '*', action: 'deny' },
    ],
  }
  const read = decode(schema, policy)
  assert.ok(read.ok)
  assert.deepEqual(read.value.rules.map((r) => r.action), ['allow', 'deny'])
  assert.equal(decodeStrict(schema, { ...policy, extra: 1 }).ok, false)
  assert.deepEqual(defaultToolPolicy, { defaultAction: 'ask', rules: [] })
})
